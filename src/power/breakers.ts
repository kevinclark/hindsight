/**
 * How hot is a breaker, as the maker's own trip curve sees it?
 *
 * A thermal breaker trips when its bimetal body has heated enough, and it heats with current squared. Each datasheet
 * gives a band: the earliest an in-spec breaker may trip (the `fast` edge) and the latest (the `slow` edge), against
 * current as a percent of rating. Each edge is modelled as up to three first-order heating stages (time constants
 * `taus`, weights `weights`) driven by x² = (amps / rating)². The edge trips when the weighted heat reaches
 * `tripRatio`². `heat()` reports that as a share: 1.0 (100 %) means this edge trips.
 *
 * The numbers are in breaker-curves.json (datasheet points and fits, regenerated by scripts/fit-breakers.ts). Not
 * modelled: ambient temperature (the datasheets are at 25 °C), a breaker that has already tripped, loose lugs.
 * Contract: docs/contracts/breaker-heat.md.
 */
import curves from './breaker-curves.json' with { type: 'json' }

export type EdgeName = 'fast' | 'slow'

/** One edge of a family's trip band, with the fit's error against the datasheet points. */
export interface BreakerEdge {
  /** Heating time constants, seconds. */
  taus: number[]
  /** Each stage's share of the heat (adds up to 1). */
  weights: number[]
  /** The ratio of current to rating, at long run, below which this edge never trips. */
  tripRatio: number
  /** Datasheet points: [percent of rating, seconds to trip from cold]. */
  points: [number, number][]
  /** Error of the fit at the points, as a share of current (what a warning acts on) and of time. */
  fitError: { currentRms: number; currentWorst: number; timeRms: number; timeWorst: number }
}

/** One family of breakers that share a curve (per percent of rating). */
export interface BreakerFamily {
  id: string
  /** 'main': the 120 A main breaker (R609); 'pdp': a breaker on a power distribution channel (R619). */
  kind: 'main' | 'pdp'
  maker: string
  parts: string[]
  ratingsA: number[]
  method: string
  datasheets: { title: string; url: string; fetched: string; sha256?: string; revision?: string; fetchedVia?: string }[]
  notes?: string
  edges: Record<EdgeName, BreakerEdge>
}

export const BREAKERS: readonly BreakerFamily[] = curves.breakers as unknown as BreakerFamily[]

/** The family with this id ('bussmann', 'rev-ato', ...), or undefined. */
export function breakerFamily(id: string): BreakerFamily | undefined {
  return BREAKERS.find((f) => f.id === id)
}

/**
 * The edge's heat at every sample, as a share of what trips it (1 = this edge trips). `amps` is the current (its size
 * counts, not its sign) sampled every `dt` seconds, `ratingA` the breaker's rating. The breaker is cold before the
 * first sample. Each stage takes the exact step `1 − exp(−dt/τ)`, so a time constant shorter than `dt` is stable.
 */
export function heat(amps: Float64Array, dt: number, ratingA: number, edge: BreakerEdge): Float64Array {
  const n = edge.taus.length
  const keep = edge.taus.map((tau) => 1 - Math.exp(-dt / tau))
  const stages = new Float64Array(n)
  const limit = edge.tripRatio * edge.tripRatio
  const out = new Float64Array(amps.length)
  for (let i = 0; i < amps.length; i++) {
    const x = amps[i] / ratingA
    const x2 = x * x
    let sum = 0
    for (let s = 0; s < n; s++) {
      stages[s] += (x2 - stages[s]) * keep[s]
      sum += edge.weights[s] * stages[s]
    }
    out[i] = sum / limit
  }
  return out
}

/** The heat a constant current (as a share of the rating) reaches after `seconds` from cold, as a share of the trip. */
function heatAfter(x: number, seconds: number, edge: BreakerEdge): number {
  let sum = 0
  for (let s = 0; s < edge.taus.length; s++) sum += edge.weights[s] * (1 - Math.exp(-seconds / edge.taus[s]))
  return (x * x * sum) / (edge.tripRatio * edge.tripRatio)
}

const LONGEST_SECONDS = 1e7

/**
 * Seconds from cold until a constant current trips this edge. `percent` is the current as a percent of the rating.
 * Infinity when the current never gets there: at or below the edge's long-run limit.
 */
export function tripSeconds(percent: number, edge: BreakerEdge): number {
  const x = percent / 100
  if (!(heatAfter(x, LONGEST_SECONDS, edge) > 1)) return Infinity
  let lo = 0
  let hi = 1
  while (heatAfter(x, hi, edge) < 1) hi *= 2
  for (let i = 0; i < 100; i++) {
    const mid = (lo + hi) / 2
    if (heatAfter(x, mid, edge) >= 1) hi = mid
    else lo = mid
  }
  return hi
}

/** The constant current (A) that just reaches 100 % of this edge in `seconds` from cold: below it, the edge holds that long. */
export function steadyAmps(seconds: number, ratingA: number, edge: BreakerEdge): number {
  return ratingA * Math.sqrt(1 / heatAfter(1, seconds, edge))
}
